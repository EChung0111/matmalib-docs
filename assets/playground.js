/* No runtime downloads until Run. All DOM writes use textContent or safe URLs. */
(() => {
  "use strict";
  const script = document.currentScript;
  const workerURL = new URL("python-worker.js", script.src);
  let worker = null;
  let active = null;
  let sequence = 0;
  const cells = [];
  const downloadURLs = [];

  function button(label, action) {
    const element = document.createElement("button");
    element.type = "button";
    element.textContent = label;
    element.dataset.action = action;
    return element;
  }
  function setBusy(value) {
    cells.forEach(cell => {
      cell.run.disabled = value;
      cell.reset.disabled = value;
      cell.stop.hidden = !(value && cell === active);
    });
  }
  function clearOutput(cell) {
    cell.urls.forEach(URL.revokeObjectURL);
    cell.urls = [];
    cell.output.replaceChildren();
  }
  function textOutput(cell, value, error = false) {
    if (!value) return;
    const pre = document.createElement("pre");
    pre.textContent = value;
    if (error) pre.className = "lab-error";
    cell.output.append(pre);
  }
  function finish(cell, message) {
    cell.status.textContent = message;
    setBusy(false);
    cell.editor.removeAttribute("aria-busy");
    active = null;
  }
  function discardWorker() {
    worker?.terminate();
    worker = null;
  }
  function getWorker() {
    if (worker) return worker;
    worker = new Worker(workerURL);
    worker.onmessage = ({ data }) => {
      const cell = active;
      if (!cell || data.id !== cell.id) return;
      if (data.type === "status") { cell.status.textContent = data.message; return; }
      if (data.type === "fatal") {
        textOutput(cell, data.error, true);
        finish(cell, "Could not run. Check your connection and retry, or follow the local setup guide.");
        discardWorker();
        return;
      }
      textOutput(cell, data.stdout);
      textOutput(cell, data.stderr);
      textOutput(cell, data.error, true);
      (data.figures || []).forEach((png, i) => {
        const image = document.createElement("img");
        image.src = `data:image/png;base64,${png}`;
        image.alt = `Figure ${i + 1} generated by this Python example`;
        cell.output.append(image);
      });
      (data.files || []).forEach(file => {
        const bytes = Uint8Array.from(atob(file.data), c => c.charCodeAt(0));
        const url = URL.createObjectURL(new Blob([bytes], { type: "application/octet-stream" }));
        cell.urls.push(url);
        downloadURLs.push(url);
        const link = document.createElement("a");
        link.className = "lab-download";
        link.href = url;
        link.download = file.name.split("/").pop();
        link.textContent = `Download ${file.name}`;
        cell.output.append(link);
      });
      if (!cell.output.childNodes.length) textOutput(cell, "Completed without printed output.");
      finish(cell, data.error ? "Python error — edit the example and run again." : "Complete · edit the code to explore further.");
    };
    worker.onerror = event => {
      if (active) {
        textOutput(active, event.message || "The Python worker could not start.", true);
        finish(active, "Runtime error. Retry or use the local setup guide.");
      }
      discardWorker();
    };
    return worker;
  }
  function run(cell) {
    if (active) return;
    active = cell;
    cell.id = ++sequence;
    clearOutput(cell);
    cell.status.textContent = "Starting Python…";
    cell.editor.setAttribute("aria-busy", "true");
    setBusy(true);
    try { getWorker().postMessage({ id: cell.id, code: cell.editor.value }); }
    catch (error) {
      textOutput(cell, String(error), true);
      finish(cell, "Browser could not start Python. Use a current browser or run locally.");
      discardWorker();
    }
  }
  document.querySelectorAll("pre.pyodide").forEach((pre, index) => {
    const original = pre.textContent.trimEnd();
    const wrapper = document.createElement("section");
    wrapper.className = "lab";
    wrapper.setAttribute("aria-label", `Interactive Python example ${index + 1}`);
    const bar = document.createElement("div");
    bar.className = "lab-bar";
    const label = document.createElement("span");
    label.className = "lab-label";
    label.textContent = "PYTHON · LIVE";
    const runButton = button("▶ Run", "run");
    runButton.title = "Run Python (Ctrl or Command + Enter)";
    const stop = button("Stop", "stop");
    stop.hidden = true;
    const reset = button("Reset", "reset");
    const copy = button("Copy", "copy");
    bar.append(label, copy, reset, stop, runButton);
    const editor = document.createElement("textarea");
    editor.value = original;
    editor.rows = Math.min(24, Math.max(5, original.split("\n").length + 1));
    editor.spellcheck = false;
    editor.autocomplete = "off";
    editor.autocapitalize = "off";
    editor.setAttribute("aria-label", `Python source for example ${index + 1}`);
    const status = document.createElement("div");
    status.className = "lab-status";
    status.setAttribute("role", "status");
    status.textContent = "Edit and run · first run downloads Python and scientific packages · Ctrl/⌘ + Enter";
    const output = document.createElement("div");
    output.className = "lab-output";
    output.setAttribute("aria-label", "Python output");
    const cell = { wrapper, editor, status, output, run: runButton, reset, stop, urls: [] };
    cells.push(cell);
    runButton.addEventListener("click", () => run(cell));
    stop.addEventListener("click", () => {
      discardWorker();
      finish(cell, "Stopped. Python memory was cleared; run again to restart.");
    });
    reset.addEventListener("click", () => {
      editor.value = original;
      clearOutput(cell);
      status.textContent = "Original example restored. Each run starts with fresh Python variables.";
    });
    copy.addEventListener("click", async () => {
      try { await navigator.clipboard.writeText(editor.value); status.textContent = "Code copied."; }
      catch { editor.focus(); editor.select(); status.textContent = "Select and copy the code with Ctrl/⌘ + C."; }
    });
    editor.addEventListener("keydown", event => {
      if ((event.ctrlKey || event.metaKey) && event.key === "Enter") { event.preventDefault(); run(cell); }
      // Tab keeps its normal focus-navigation behavior for keyboard access.
    });
    wrapper.append(bar, editor, status, output);
    pre.replaceWith(wrapper);
  });
  window.addEventListener("pagehide", event => {
    if (active) finish(active, "Stopped on navigation. Run again to restart Python.");
    discardWorker();
    if (!event.persisted) downloadURLs.forEach(URL.revokeObjectURL);
  });
})();
